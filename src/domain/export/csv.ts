export type CsvTransaction = {
  date: string;
  type: 'income' | 'expense';
  amountMinor: number;
  currency: string;
  categoryName: string;
  paymentMethodName: string;
  note: string;
  recurring: boolean;
};

export const CSV_HEADER = ['Date', 'Type', 'Amount', 'Currency', 'Category', 'Payment method', 'Note', 'Recurring'];

/** 125050 -> "1250.50". Integer arithmetic only; never goes through a float. */
export function minorToDecimal(minor: number): string {
  if (!Number.isSafeInteger(minor)) throw new Error('Amount is not a safe integer.');
  const sign = minor < 0 ? '-' : '';
  const abs = Math.abs(minor);
  const whole = Math.floor(abs / 100);
  const frac = String(abs % 100).padStart(2, '0');
  return `${sign}${whole}.${frac}`;
}

/**
 * Spreadsheets treat cells starting with = + - @ (or tab/CR) as formulas. Free text is prefixed with an
 * apostrophe so imported notes can never execute. Numeric columns are generated by us and are not passed through here.
 */
export function neutralizeFormula(text: string): string {
  return /^[=+\-@\t\r]/.test(text) ? `'${text}` : text;
}

/** RFC 4180 field quoting. */
export function csvField(value: string): string {
  return /[",\r\n]/.test(value) ? `"${value.replace(/"/g, '""')}"` : value;
}

export function transactionsToCsv(rows: CsvTransaction[], options: { bom?: boolean } = {}): string {
  const lines = [CSV_HEADER.map(csvField).join(',')];
  for (const r of rows) {
    lines.push(
      [
        r.date,
        r.type,
        minorToDecimal(r.amountMinor),
        r.currency,
        csvField(neutralizeFormula(r.categoryName)),
        csvField(neutralizeFormula(r.paymentMethodName)),
        csvField(neutralizeFormula(r.note)),
        r.recurring ? 'yes' : 'no',
      ].join(','),
    );
  }
  const body = lines.join('\r\n') + '\r\n';
  return options.bom ? `﻿${body}` : body;
}
